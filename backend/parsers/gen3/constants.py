def level_from_exp(exp: int, growth_rate: int) -> int:
    """Calculate Pokémon level from experience points using Gen 3 growth rate formulas."""
    if exp <= 0:
        return 1
    for lv in range(100, 0, -1):
        if exp >= _exp_at_level(lv, growth_rate):
            return lv
    return 1


def _exp_at_level(n: int, rate: int) -> int:
    if n <= 1:
        return 0
    if rate == 0:  # Medium Fast
        return n ** 3
    if rate == 1:  # Erratic
        if n <= 50:
            return (n ** 3) * (100 - n) // 50
        if n <= 68:
            return (n ** 3) * (150 - n) // 100
        if n <= 98:
            return (n ** 3) * ((1911 - 10 * n) // 3) // 500
        return (n ** 3) * (160 - n) // 100
    if rate == 2:  # Fluctuating
        if n <= 15:
            return (n ** 3) * (((n + 1) // 3) + 24) // 50
        if n <= 35:
            return (n ** 3) * (n + 14) // 50
        return (n ** 3) * ((n // 2) + 32) // 50
    if rate == 3:  # Medium Slow
        return max(0, (6 * n ** 3 // 5) - 15 * n ** 2 + 100 * n - 140)
    if rate == 4:  # Fast
        return 4 * n ** 3 // 5
    if rate == 5:  # Slow
        return 5 * n ** 3 // 4
    return n ** 3
